#!/usr/bin/env python3
"""Render the reference tables as one readable Markdown page (docs/tables.md).

The JSON files in reference/ are the data; docs/tables.md is generated from them
and must not be edited by hand:  python tools/render_tables.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent


def _load(repo: Path, rel: str):
    return json.loads((repo / rel).read_text(encoding="utf-8"))


def _vals(items) -> str:
    return "، ".join(i["value"] for i in items) if items else "—"


def _statuses(node, out=None) -> set[str]:
    out = set() if out is None else out
    if isinstance(node, dict):
        if "src" in node and "status" in node:
            out.add(node["status"])
        for v in node.values():
            _statuses(v, out)
    elif isinstance(node, list):
        for v in node:
            _statuses(v, out)
    return out


def render(repo: Path = REPO) -> str:
    abwab = _load(repo, "reference/abwab.bina-35.json")
    forms = _load(repo, "reference/forms.wright.json")
    groups = {g["id"]: g for g in abwab["groups"]}
    L = ["# Reference tables", "",
         "Generated from `reference/*.json` by `tools/render_tables.py`. Do not edit this file by hand.", "",
         "## The 35 abwāb of *Matn al-Bināʾ*", "", abwab["collation"], "",
         "The column *checked* shows the statuses of the Arabic values of the row (pattern, model verb, maṣdars, use, examples).", ""]
    current = None
    for b in abwab["abwab"]:
        if b["group"] != current:
            current = b["group"]; g = groups[current]
            L += ["", f"### {g['label_ar']['value']} ({g['label_en']}, {g['count']})", "",
                  "| # | Pattern | Model verb | Maṣdar of the model | Built for | Examples | Western | Page | Checked |",
                  "|---|---|---|---|---|---|---|---|---|"]
        w = b["wazn"]; m = b["mawzun"]
        west = ", ".join(f"{x['value']} ({x['relation']})" for x in b["western"])
        page = w["past"]["src"][0]["loc"]
        arabic = {k: b[k] for k in ("wazn", "mawzun", "examples")} | {"bina": b["bina"]["ar"]}
        st = ", ".join(sorted(_statuses(arabic)))
        L.append(f"| {b['number']} | {w['past']['value']} {w['imperfect']['value']} | {m['past']['value']} {m['imperfect']['value']} | "
                 f"{_vals(m.get('masdar'))} | {b['bina']['ar']['value']} | {_vals(b.get('examples'))} | {west} | {page} | {st} |")
    L += ["", "## Forms after Wright", "", forms["collation"], "",
          "| Form | Pattern | Treated in | Status |", "|---|---|---|---|"]
    for f in forms["forms"]:
        L.append(f"| {f['id']} | {f['pattern']['value']} | {f['treated_in']['value']} | {f['pattern']['status']} |")
    L += ["", f"**Imperfect vowel of Form I.** {forms['imperfect_vowel']['value']} ({forms['imperfect_vowel']['src'][0]['loc']}; status {forms['imperfect_vowel']['status']})", ""]
    return "\n".join(L)


if __name__ == "__main__":
    out = REPO / "docs" / "tables.md"
    out.write_text(render(), encoding="utf-8")
    print(f"wrote {out.relative_to(REPO)}")
